#!/usr/bin/env python3
"""Generates the app's theme from Design/0.4/tokens.json, the one source for colors and type:

    Glassine/Resources/Theme.xcassets   colors, light + dark (Xcode makes Color.ink, NSColor.paper, …)
    Glassine/UI/ThemeTokens.swift       type scale, radii, perforation

    python3 scripts/theme-tokens.py     # after changing tokens.json; commit the results
"""
import json
import os
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TOKENS = os.path.join(ROOT, "Design", "0.4", "tokens.json")
ASSETS = os.path.join(ROOT, "Glassine", "Resources", "Theme.xcassets")
SWIFT = os.path.join(ROOT, "Glassine", "UI", "ThemeTokens.swift")

# Scene-only tokens stay out of the app.
SKIP = {"desk", "screen", "notch"}
# Token → asset name. `blue` would clash with Color.blue; the semantic blue is the Stamp of DECISIONS.md.
RENAME = {"blue": "postmark", "blue_deep": "stamp"}


def camel(name):
    head, *rest = name.split("_")
    return head + "".join(part.capitalize() for part in rest)


def color(hex_):
    h = hex_.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) for i in (0, 2, 4))
    return {"color-space": "srgb",
            "components": {"red": f"{r / 255:.3f}", "green": f"{g / 255:.3f}", "blue": f"{b / 255:.3f}",
                           "alpha": "1.000"}}


def colorset(name, light, dark):
    path = os.path.join(ASSETS, f"{name}.colorset")
    os.makedirs(path)
    with open(os.path.join(path, "Contents.json"), "w") as f:
        json.dump({"colors": [
            {"idiom": "universal", "color": color(light)},
            {"idiom": "universal", "appearances": [{"appearance": "luminosity", "value": "dark"}],
             "color": color(dark)},
        ], "info": {"author": "xcode", "version": 1}}, f, indent=2)
        f.write("\n")


def swift_number(value):
    return f"{value:g}"


def main():
    with open(TOKENS) as f:
        tokens = json.load(f)

    shutil.rmtree(ASSETS, ignore_errors=True)
    os.makedirs(ASSETS)
    with open(os.path.join(ASSETS, "Contents.json"), "w") as f:
        json.dump({"info": {"author": "xcode", "version": 1}}, f, indent=2)
        f.write("\n")

    light, dark = tokens["light"], tokens["dark"]
    names = []
    for key in light:
        if key in SKIP:
            continue
        name = RENAME.get(key, camel(key))
        colorset(name, light[key], dark[key])
        names.append(name)
    for accent, pairs in tokens["accents"].items():
        if not isinstance(pairs, dict):
            continue  # "system" comes from macOS
        title = accent.capitalize()
        colorset(f"accent{title}", pairs["light"]["fill"], pairs["dark"]["fill"])
        colorset(f"onAccent{title}", pairs["light"]["on"], pairs["dark"]["on"])
        names += [f"accent{title}", f"onAccent{title}"]

    scale = tokens["type"]["scale"]
    lines = [
        "// Generated by scripts/theme-tokens.py from Design/0.4/tokens.json — edit the tokens, not this file.",
        "import CoreGraphics",
        "",
        "enum ThemeTokens {",
        "    struct TypeStyle {",
        "        enum Family { case serif, sans, mono }",
        "        let family: Family",
        "        let size: CGFloat",
        "        /// Variable-font weight (CSS scale: 400 regular, 700 bold); nil for the system default.",
        "        let weight: CGFloat?",
        "        let tracking: CGFloat",
        "        let italic: Bool",
        "        let uppercase: Bool",
        "    }",
        "",
    ]
    for role, s in scale.items():
        weight = swift_number(s["weight"]) if "weight" in s else "nil"
        lines.append(
            f"    static let {role} = TypeStyle(family: .{s['family']}, size: {swift_number(s['size'])}, "
            f"weight: {weight}, tracking: {swift_number(s.get('tracking', 0))}, "
            f"italic: {str(s.get('italic', False)).lower()}, uppercase: {str(s.get('uppercase', False)).lower()})")
    radius = tokens["radius"]
    perf = tokens["perforation"]
    lines += [
        "",
        "    enum Radius {",
        *(f"        static let {k}: CGFloat = {swift_number(v)}" for k, v in radius.items() if isinstance(v, (int, float))),
        "    }",
        "",
        "    /// Postage-stamp perforation: hole radius and spacing along the edge, in points.",
        "    enum Perforation {",
        f"        static let hole: CGFloat = {swift_number(perf['hole'])}",
        f"        static let pitch: CGFloat = {swift_number(perf['pitch'])}",
        "    }",
        "}",
        "",
    ]
    with open(SWIFT, "w") as f:
        f.write("\n".join(lines))

    print(f"{os.path.relpath(ASSETS, ROOT)}: {len(names)} colors ({', '.join(names)})")
    print(os.path.relpath(SWIFT, ROOT))


if __name__ == "__main__":
    main()
